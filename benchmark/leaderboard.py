"""Generate the settled-gate FTC benchmark leaderboard (Artifact F) from committed evidence.

Merges the actuator-fault battery (``evidence/program/taxonomy_settled.json`` + the
disturbance-observer result ``evidence/program/gain_bias_dob.json``) and the sensor-fault
regime classification (``evidence/program/sensor_faults.json``) into ``benchmark/leaderboard.md``
— a Markdown leaderboard for the benchmark README. All entries use the SAME structurally
held-out faults (seed 7000, n=500/cell) and the SAME settled-science gate, so they are directly
comparable; every number traces to a producer's evidence (regenerable via ``tools/reproduce``).

Run from repo root:  python -m benchmark.leaderboard
"""

from __future__ import annotations

import json
from pathlib import Path

TAX = json.loads(Path("evidence/program/taxonomy_settled.json").read_text())
DOB = json.loads(Path("evidence/program/gain_bias_dob.json").read_text())
SENS = json.loads(Path("evidence/program/sensor_faults.json").read_text())
OUT = Path("benchmark/leaderboard.md")

ACT_CLASSES = ["sign", "gain", "gain_bias", "total_loss"]
ACT_HEAD = {"sign": "SIGN", "gain": "GAIN", "gain_bias": "GAIN+BIAS", "total_loss": "LOSS"}

# (display, source, key); source: tax -> taxonomy_settled, dob -> gain_bias_dob
ENTRIES: list[tuple[str, str, str]] = [
    ("PD (fault-unaware)", "tax", "pd_fault_unaware"),
    ("PID (fault-unaware)", "tax", "pid_unaware"),
    ("Classical adaptive (sign-ID)", "tax", "classical_adaptive"),
    ("ICL-adaptive [lit.]", "tax", "icl_adaptive_lit"),
    ("Nussbaum-gain [lit.]", "tax", "nussbaum_adaptive_lit"),
    ("End-to-end GRU+PPO", "tax", "gru_ppo_fair"),
    ("RMA student, latched [WS1]", "tax", "rma_student_latched"),
    ("**RMA + disturbance observer [ours]**", "dob", "rma_widebias_plus_dob"),
    ("_Privileged teacher (gain oracle)_", "tax", "teacher_privileged"),
    ("_Bias-feedforward oracle (g+b)_", "dob", "teacher_bias_ff_oracle"),
]


def _rate(source: str, key: str, fclass: str) -> str:
    try:
        if source == "tax":
            r = TAX["by_class"][fclass][key]["settled_science"]["rate"]
        else:
            r = DOB["by_class"][fclass][key]["settled_science_rate"]
        return f"{100 * float(r):.1f}"
    except KeyError:
        return "—"


def _actuator_table() -> str:
    head = "| Controller | " + " | ".join(ACT_HEAD[c] for c in ACT_CLASSES) + " |"
    sep = "|" + "---|" * (len(ACT_CLASSES) + 1)
    rows = [
        f"| {label} | " + " | ".join(_rate(src, key, c) for c in ACT_CLASSES) + " |"
        for label, src, key in ENTRIES
    ]
    return "\n".join([head, sep, *rows])


def _sensor_table() -> str:
    head = "| Sensor fault | RMA settled-% | final (deg) | regime |"
    sep = "|---|---|---|---|"
    rows = []
    for arm, by in SENS["by_arm"].items():
        r = by["rma_student_latched"]
        rows.append(
            f"| {arm} | {100 * r['settled_science_rate']:.1f} | "
            f"{r['final_deg_median']:.3f} | {SENS['classification'][arm]} |"
        )
    return "\n".join([head, sep, *rows])


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    md = f"""<!-- AUTO-GENERATED by benchmark/leaderboard.py — do not edit by hand. -->
# Settled-Gate Spacecraft FTC Benchmark — Leaderboard

Settled-science rate (%) — pointing held within **0.2°** over the final-dwell window — on the
structurally held-out TEST faults (n={TAX["n_faults"]}/cell × {TAX["n_seeds"]} seeds = 500),
same faults and gate across all rows. See `BENCHMARK.md` for the protocol.

## Actuator faults

{_actuator_table()}

GAIN+BIAS (constant additive actuator bias) is 0% for every classical, learned, and RMA
controller — and for the privileged gain oracle (an integral-free law cannot null a constant
bias). The RMA student composed with a **disturbance observer** is the only deployable
controller to recover it; the bias-feedforward oracle is the upper bound. A dead axis (LOSS) is
uncontrollable for all (shield-only).

## Sensor faults (deployed RMA, true-state scored)

{_sensor_table()}

A sensor bias is controllable within the 0.2° gate and offsets to exactly −bias beyond it;
star-tracker dropout and a stuck attitude sensor remove position feedback (shield-only). These
are fundamental sensor-regime limits (the oracle matches the controller).
"""
    OUT.write_text(md, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
