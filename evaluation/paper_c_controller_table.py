"""Paper C, C-2: the definitive controller taxonomy table (settled gate, held-out faults).

Merges the WS1 controller battery (``evidence/program/taxonomy_settled.json``) with the
GAIN_BIAS disturbance-observer result (``evidence/program/gain_bias_dob.json``) into one
booktabs table over the four structurally-held-out fault classes. Both evidence files use the
SAME held-out faults (``heldout_test_faults(seed=7000)``, n=50/cell x 10 seeds) and the SAME
settled-science gate, so the numbers are directly comparable.

The story the table tells. GAIN_BIAS is 0% for EVERY classical, learned, and RMA controller in
the WS1 battery, and for the privileged gain oracle too, which is the integral-free
architectural limit. The estimate-then-control RMA student composed with the disturbance observer
(ours) is the only deployable controller to recover it, with no SIGN/GAIN regression; the
bias-feedforward oracle is the upper bound.

Run from repo root:  python -m evaluation.paper_c_controller_table
"""

from __future__ import annotations

import json
from pathlib import Path

TAX = json.loads(Path("evidence/program/taxonomy_settled.json").read_text())
DOB = json.loads(Path("evidence/program/gain_bias_dob.json").read_text())
SENS = json.loads(Path("evidence/program/sensor_faults.json").read_text())
OUT = Path("paper/controller_study/tables/tab_battery.tex")
SENS_OUT = Path("paper/controller_study/tables/tab_sensor.tex")
CLASSES = ["sign", "gain", "gain_bias", "total_loss"]
COLHEAD = {"sign": "SIGN", "gain": "GAIN", "gain_bias": "GAIN+BIAS", "total_loss": "LOSS"}
SENS_LABEL = {
    "sensor_bias_0p1deg": "Sensor bias $0.1^\\circ$",
    "sensor_bias_0p2deg": "Sensor bias $0.2^\\circ$",
    "sensor_bias_0p3deg": "Sensor bias $0.3^\\circ$",
    "sensor_bias_0p5deg": "Sensor bias $0.5^\\circ$",
    "star_tracker_dropout": "Star-tracker dropout",
    "stuck_measurement": "Stuck measurement",
}

# (display label, source, key). source: "tax" -> taxonomy_settled, "dob" -> gain_bias_dob.
ROWS: list[tuple[str, str, str]] = [
    ("PD (fault-unaware)", "tax", "pd_fault_unaware"),
    ("Classical adaptive (sign-ID)", "tax", "classical_adaptive"),
    ("ICL-adaptive [lit.]", "tax", "icl_adaptive_lit"),
    ("Nussbaum-gain [lit.]", "tax", "nussbaum_adaptive_lit"),
    ("End-to-end GRU+PPO", "tax", "gru_ppo_fair"),
    ("RMA student, latched [WS1]", "tax", "rma_student_latched"),
    ("\\textbf{RMA + disturbance obs.\\ [ours]}", "dob", "rma_widebias_plus_dob"),
    ("Privileged teacher (gain oracle)", "tax", "teacher_privileged"),
    ("Bias-feedforward oracle (g+b)", "dob", "teacher_bias_ff_oracle"),
]
# rule rows: separate baselines | RMA family | oracles
MIDRULE_AFTER = {"End-to-end GRU+PPO", "\\textbf{RMA + disturbance obs.\\ [ours]}"}


def _rate(source: str, key: str, fclass: str) -> float | None:
    try:
        if source == "tax":
            return float(TAX["by_class"][fclass][key]["settled_science"]["rate"])
        return float(DOB["by_class"][fclass][key]["settled_science_rate"])
    except KeyError:
        return None


def _cell(r: float | None, bold: bool) -> str:
    if r is None:
        return "--"
    s = f"{100 * r:.1f}\\%"
    return f"\\textbf{{{s}}}" if (bold and r > 0) else s


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "% AUTO-GENERATED by evaluation.paper_c_controller_table.py",
        "% from taxonomy_settled.json (WS1 battery) + gain_bias_dob.json (DOB).",
        "\\begin{table}[h]\\centering\\small",
        "\\caption{Definitive controller battery, reporting settled-science rate "
        "($\\leq0.2^\\circ$ held over the final dwell) on the four structurally held-out fault "
        "classes ($n{=}500$/cell, same faults and gate across rows). \\textbf{GAIN+BIAS is 0\\% "
        "for every classical, learned, and RMA controller, and for the privileged gain oracle, "
        "which is the integral-free architectural limit; the RMA student composed with the "
        "disturbance observer is the only deployable controller to recover it}, with no SIGN/GAIN "
        "regression. A dead axis (LOSS) is uncontrollable (shield-only) for all.}",
        "\\label{tab:battery}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Controller & " + " & ".join(COLHEAD[c] for c in CLASSES) + " \\\\",
        "\\midrule",
    ]
    for label, source, key in ROWS:
        bold = "ours" in label
        cells = [_cell(_rate(source, key, c), bold) for c in CLASSES]
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
        if label in MIDRULE_AFTER:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")
    _write_sensor_table()
    # also echo the GAIN+BIAS column for a quick sanity check
    print("GAIN+BIAS column:")
    for label, source, key in ROWS:
        print(f"  {label:42s} {_cell(_rate(source, key, 'gain_bias'), False)}")


def _write_sensor_table() -> None:
    """Sensor-fault regime table (deployed RMA, true-state scored) from sensor_faults.json."""
    lines = [
        "% AUTO-GENERATED by evaluation.paper_c_controller_table.py from sensor_faults.json",
        "\\begin{table}[h]\\centering\\small",
        "\\caption{Sensor-fault regimes (deployed RMA, settled gate, scored on the TRUE state). "
        "A constant attitude bias is controllable within the $0.2^\\circ$ gate and offsets to "
        "exactly $-$bias beyond it (the sensor-side analog of actuator GAIN+BIAS); a lost or "
        "stuck attitude sensor removes position feedback (shield-only, the analog of "
        "TOTAL\\_LOSS). The privileged teacher matches the controller on every row, so these "
        "are fundamental "
        "sensor-regime limits, and a sensor bias is unobservable from the corrupted measurement "
        "alone (unlike the actuator bias).}",
        "\\label{tab:sensor}",
        "\\begin{tabular}{lccl}",
        "\\toprule",
        "Sensor fault & settled-science & final pointing & regime \\\\",
        "\\midrule",
    ]
    for arm, by in SENS["by_arm"].items():
        r = by["rma_student_latched"]
        lines.append(
            f"{SENS_LABEL.get(arm, arm)} & {100 * r['settled_science_rate']:.1f}\\% & "
            f"{r['final_deg_median']:.2f}$^\\circ$ & {SENS['classification'][arm]} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    SENS_OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {SENS_OUT}")


if __name__ == "__main__":
    main()
